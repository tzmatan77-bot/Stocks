import { PremarketNewsItem, PremarketMarketPulse } from '../types';

export function getCalculatedMarketPulse(): PremarketMarketPulse {
  const now = new Date();
  
  // Calculate New York Time (UTC-4 or UTC-5 depending on DST, approx UTC-4 for September)
  const nyDate = new Date(now.toLocaleString('en-US', { timeZone: 'America/New_York' }));
  const nyHours = nyDate.getHours();
  const nyMinutes = nyDate.getMinutes();
  const nyDay = nyDate.getDay(); // 0 = Sunday, 6 = Saturday

  const nyTimeStr = nyDate.toLocaleTimeString('en-US', {
    hour: '2-digit',
    minute: '2-digit',
    hour12: true,
  });

  const israelDate = new Date(now.toLocaleString('en-US', { timeZone: 'Asia/Jerusalem' }));
  const israelTimeStr = israelDate.toLocaleTimeString('he-IL', {
    hour: '2-digit',
    minute: '2-digit',
    hour12: false,
  });

  let sessionStatus: PremarketMarketPulse['sessionStatus'] = 'PRE_MARKET';
  let minutesToOpen = 0;

  if (nyDay === 0 || nyDay === 6) {
    sessionStatus = 'WEEKEND_CLOSED';
    minutesToOpen = 0;
  } else {
    const totalMinutes = nyHours * 60 + nyMinutes;
    const marketOpenMinutes = 9 * 60 + 30; // 09:30 AM
    const marketCloseMinutes = 16 * 60; // 04:00 PM
    const preMarketStartMinutes = 4 * 60; // 04:00 AM

    if (totalMinutes < preMarketStartMinutes) {
      sessionStatus = 'WEEKEND_CLOSED'; // Overnight pre-market pending
      minutesToOpen = marketOpenMinutes - totalMinutes;
    } else if (totalMinutes >= preMarketStartMinutes && totalMinutes < marketOpenMinutes) {
      sessionStatus = 'PRE_MARKET';
      minutesToOpen = marketOpenMinutes - totalMinutes;
    } else if (totalMinutes >= marketOpenMinutes && totalMinutes < marketCloseMinutes) {
      sessionStatus = 'REGULAR_MARKET';
      minutesToOpen = 0;
    } else {
      sessionStatus = 'AFTER_HOURS';
      minutesToOpen = 0;
    }
  }

  return {
    sessionStatus,
    nyTimeStr,
    israelTimeStr,
    minutesToOpen,
    marketSentiment: 'RISK_ON',
    sp500FuturesChange: '+0.42%',
    nasdaqFuturesChange: '+0.68%',
    tenYearTreasuryYield: '4.18% (-3 bps)',
    vixLevel: '14.85 (-0.45)',
    dailyMacroBriefHe: 'החוזים העתידיים בוול-סטריט נסחרים בעליות שערים לקראת פתיחת המסחר, בהובלת מניות השבבים וענקיות הטכנולוגיה. תשואות האג"ח ל-10 שנים יורדות קלות ל-4.18%, מה שמעניק רוח גבית למכפילי הרווח של חברות איכות צומחות.',
    dailyMacroBriefEn: 'US equity index futures edge higher ahead of the opening bell, led by semiconductors and mega-cap tech. 10-year Treasury yields pull back 3 bps to 4.18%, supporting valuation multiples for high-ROIC compounders.',
  };
}

